CREATE TABLE estudiante (
    documentoidentidad VARCHAR2(20)  NOT NULL,
    nombre             VARCHAR2(60)  NOT NULL,
    apellido           VARCHAR2(60)  NOT NULL,
    universidad        VARCHAR2(100) NOT NULL,
    programacursa      VARCHAR2(100) NOT NULL,
    correo             VARCHAR2(120) NOT NULL,
    telefono           VARCHAR2(15)  NOT NULL,
    CONSTRAINT pk_estudiante PRIMARY KEY (documentoidentidad),
    CONSTRAINT uq_estudiante_correo UNIQUE (correo),
    CONSTRAINT uq_estudiante_telefono UNIQUE (telefono)
);

CREATE TABLE localidad (
    idlocalidad NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre      VARCHAR2(60) NOT NULL,
    CONSTRAINT pk_localidad PRIMARY KEY (idlocalidad),
    CONSTRAINT uq_localidad_nombre UNIQUE (nombre)
);

CREATE TABLE conductor (
    documentoidentidad VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_conductor PRIMARY KEY (documentoidentidad),
    CONSTRAINT fk_conductor_estudiante FOREIGN KEY (documentoidentidad)
        REFERENCES estudiante (documentoidentidad)
);

CREATE TABLE pasajero (
    documentoidentidad VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_pasajero PRIMARY KEY (documentoidentidad),
    CONSTRAINT fk_pasajero_estudiante FOREIGN KEY (documentoidentidad)
        REFERENCES estudiante (documentoidentidad)
);

CREATE TABLE vehiculo (
    placa              VARCHAR2(10) NOT NULL,
    marca              VARCHAR2(40) NOT NULL,
    modelo             VARCHAR2(40) NOT NULL,
    anio               NUMBER(4)    NOT NULL,
    color              VARCHAR2(30) NOT NULL,
    cupos              NUMBER(2)    NOT NULL,
    documentoconductor VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_vehiculo PRIMARY KEY (placa),
    CONSTRAINT fk_vehiculo_conductor FOREIGN KEY (documentoconductor)
        REFERENCES conductor (documentoidentidad),
    CONSTRAINT ck_vehiculo_anio CHECK (anio BETWEEN 1990 AND 2100),
    CONSTRAINT ck_vehiculo_cupos CHECK (cupos > 0)
);

CREATE TABLE parada (
    idparada    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    direccion   VARCHAR2(200) NOT NULL,
    idlocalidad NUMBER        NOT NULL,
    CONSTRAINT pk_parada PRIMARY KEY (idparada),
    CONSTRAINT uq_parada_direccion UNIQUE (direccion),
    CONSTRAINT fk_parada_localidad FOREIGN KEY (idlocalidad)
        REFERENCES localidad (idlocalidad)
);

CREATE TABLE viaje (
    idviaje           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    fechasalida       DATE           NOT NULL,
    fechallegada      DATE,
    origen            VARCHAR2(200)  NOT NULL,
    idlocalidadorigen NUMBER         NOT NULL,
    sentido           VARCHAR2(20)   NOT NULL,
    ruta              VARCHAR2(500)  NOT NULL,
    distanciakm       NUMBER(6,2)    NOT NULL,
    cuposdisponibles  NUMBER(2)      NOT NULL,
    costo             NUMBER(10,2)   NOT NULL,
    estado            VARCHAR2(12)   DEFAULT 'Programado' NOT NULL,
    placa             VARCHAR2(10)   NOT NULL,
    CONSTRAINT pk_viaje PRIMARY KEY (idviaje),
    CONSTRAINT fk_viaje_localidad FOREIGN KEY (idlocalidadorigen)
        REFERENCES localidad (idlocalidad),
    CONSTRAINT fk_viaje_vehiculo FOREIGN KEY (placa)
        REFERENCES vehiculo (placa),
    CONSTRAINT ck_viaje_estado CHECK (estado IN ('Programado', 'En curso', 'Completado', 'Cancelado')),
    CONSTRAINT ck_viaje_sentido CHECK (sentido IN ('Hacia universidad', 'Desde universidad')),
    CONSTRAINT ck_viaje_distancia CHECK (distanciakm > 0),
    CONSTRAINT ck_viaje_cupos CHECK (cuposdisponibles >= 0),
    CONSTRAINT ck_viaje_costo CHECK (costo >= 0),
    CONSTRAINT ck_viaje_llegada CHECK (fechallegada IS NULL OR fechallegada > fechasalida)
);

CREATE TABLE seguimiento (
    idviaje  NUMBER NOT NULL,
    idparada NUMBER NOT NULL,
    CONSTRAINT pk_seguimiento PRIMARY KEY (idviaje, idparada),
    CONSTRAINT fk_seguimiento_viaje FOREIGN KEY (idviaje)
        REFERENCES viaje (idviaje),
    CONSTRAINT fk_seguimiento_parada FOREIGN KEY (idparada)
        REFERENCES parada (idparada)
);

CREATE TABLE solicitud (
    idsolicitud       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    estado            VARCHAR2(10) DEFAULT 'Pendiente' NOT NULL,
    fechasolicitud    DATE         DEFAULT SYSDATE NOT NULL,
    documentopasajero VARCHAR2(20) NOT NULL,
    idviaje           NUMBER       NOT NULL,
    idparada          NUMBER       NOT NULL,
    CONSTRAINT pk_solicitud PRIMARY KEY (idsolicitud),
    CONSTRAINT fk_solicitud_pasajero FOREIGN KEY (documentopasajero)
        REFERENCES pasajero (documentoidentidad),
    CONSTRAINT fk_solicitud_seguimiento FOREIGN KEY (idviaje, idparada)
        REFERENCES seguimiento (idviaje, idparada),
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('Pendiente', 'Aceptada', 'Rechazada', 'Cancelada'))
);

CREATE UNIQUE INDEX uq_solicitud_activa ON solicitud (
    CASE WHEN estado IN ('Pendiente', 'Aceptada') THEN idviaje END,
    CASE WHEN estado IN ('Pendiente', 'Aceptada') THEN documentopasajero END
);

CREATE INDEX idx_vehiculo_conductor ON vehiculo (documentoconductor);
CREATE INDEX idx_parada_localidad ON parada (idlocalidad);
CREATE INDEX idx_viaje_localidad ON viaje (idlocalidadorigen);
CREATE INDEX idx_viaje_vehiculo ON viaje (placa);
CREATE INDEX idx_seguimiento_parada ON seguimiento (idparada);
CREATE INDEX idx_solicitud_pasajero ON solicitud (documentopasajero);
CREATE INDEX idx_solicitud_seguimiento ON solicitud (idviaje, idparada);
